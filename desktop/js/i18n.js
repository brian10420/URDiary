    function getLang() {
        const saved = localStorage.getItem(LANG_KEY);
        return SUPPORTED.includes(saved) ? saved : 'zh-TW';
    }

    function setLang(lang) {
        if (SUPPORTED.includes(lang)) {
            localStorage.setItem(LANG_KEY, lang);
        }
    }

    function t(key, params) {
        const lang = getLang();
        let text = (LOCALES[lang] && LOCALES[lang][key]) ||
                   (LOCALES['zh-TW'] && LOCALES['zh-TW'][key]);
        if (text === undefined) {
            console.warn(`[i18n] missing key: ${key}`);
            return key;
        }
        if (params) {
            Object.keys(params).forEach(name => {
                text = text.replace(new RegExp(`\\{${name}\\}`, 'g'), params[name]);
            });
        }
        return text;
    }

    // 靜態 DOM 節點翻譯
    // (data-i18n / data-i18n-placeholder / data-i18n-title / data-i18n-aria-label)
    function applyDom(root) {
        const scope = root || document;
        scope.querySelectorAll('[data-i18n]').forEach(el => {
            el.textContent = t(el.getAttribute('data-i18n'));
        });
        scope.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
        });
        scope.querySelectorAll('[data-i18n-title]').forEach(el => {
            el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
        });
        // v2.3 task 2.1：底部分頁列（.tab-bar）用得到——它的 aria-label 不是
        // 元素自身的文字內容（元素內還有圖示 <i> 子節點，不能用 data-i18n
        // 直接指到它，textContent 賦值會把圖示一起清掉）。
        scope.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
            el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
        });
        document.documentElement.setAttribute('lang', getLang());
        document.title = t('app.title');
    }

    // 日期地區碼（diary_module 等的 toLocaleDateString 用）
    function dateLocale() {
        return getLang() === 'en' ? 'en-US' : 'zh-TW';
    }

    document.addEventListener('DOMContentLoaded', function() {
        applyDom();
    });

    return { t, getLang, setLang, applyDom, dateLocale };
