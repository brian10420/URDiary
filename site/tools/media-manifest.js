#!/usr/bin/env node
/**
 * Writes site/media/manifest.json from the videos actually present in site/media/.
 * The page only requests files listed there, so a video that has not been produced yet costs
 * no request (and no 404 in the console); adding one is just: drop the file into site/media/,
 * run this (the Pages workflow runs it on every deploy), done.
 *
 *   node site/tools/media-manifest.js            write the manifest
 *   node site/tools/media-manifest.js --check    exit 1 if the manifest is out of date
 */
'use strict';

const fs = require('fs');
const path = require('path');

const MEDIA = path.resolve(__dirname, '..', 'media');
const OUT = path.join(MEDIA, 'manifest.json');
const VIDEO = /\.(mp4|webm)$/i;

const files = fs.existsSync(MEDIA)
    ? fs.readdirSync(MEDIA).filter((name) => VIDEO.test(name) && fs.statSync(path.join(MEDIA, name)).isFile()).sort()
    : [];
const body = JSON.stringify({
    note: 'Generated by site/tools/media-manifest.js from the videos present in site/media/. The page only requests listed files.',
    files,
}, null, 2) + '\n';

if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== body) {
        console.error(`media-manifest: site/media/manifest.json is out of date (videos present: ${files.join(', ') || 'none'})`);
        process.exit(1);
    }
    console.log(`media-manifest: up to date (${files.length} video${files.length === 1 ? '' : 's'})`);
} else {
    fs.mkdirSync(MEDIA, { recursive: true });
    fs.writeFileSync(OUT, body);
    console.log(`media-manifest: wrote ${files.length} video${files.length === 1 ? '' : 's'}: ${files.join(', ') || '(none yet)'}`);
}
