#!/usr/bin/env node
/**
 * Lists the media actually present in public/media/ (gitignored) and writes
 * src/generated/media-manifest.ts (gitignored), which <MediaSlot> / the audio tracks read at
 * bundle time: a present file is played, a missing one becomes a labelled placeholder (pictures)
 * or silence (sound). Run automatically before dev / render / check (`npm run gen`).
 *
 *   node scripts/media-manifest.mjs            write the manifest, print the slot table
 *   node scripts/media-manifest.mjs --quiet    write it, one summary line
 *
 * Each file is probed (duration, size, fps) so narration lengths can time the subtitles and the
 * music ducking. Probes are cached by size + mtime in src/generated/.media-probe-cache.json.
 * Fails on: two files for one id (G1.mp4 + G1.mov), a picture slot holding audio, etc.
 */
import {mkdirSync, readFileSync, readdirSync, statSync, writeFileSync} from 'node:fs';
import {dirname, extname, join, relative, resolve} from 'node:path';
import {AUDIO_EXT, IMAGE_EXT, VIDEO_EXT} from '../src/data/media.ts';
import {expectedMedia} from '../src/data/expected-media.ts';
import {MEDIA, PROJECT, PUBLIC, exists, findFfprobe, probe} from './lib/tools.mjs';

const OUT = resolve(PROJECT, 'src/generated/media-manifest.ts');
const CACHE = resolve(PROJECT, 'src/generated/.media-probe-cache.json');
const quiet = process.argv.includes('--quiet');

const kindOf = (ext) =>
  VIDEO_EXT.includes(ext) ? 'video' : IMAGE_EXT.includes(ext) ? 'image' : AUDIO_EXT.includes(ext) ? 'audio' : null;

const walk = (dir) =>
  !exists(dir)
    ? []
    : readdirSync(dir, {withFileTypes: true}).flatMap((d) => {
        const p = join(dir, d.name);
        if (d.name.startsWith('.')) return [];
        if (d.isDirectory()) return walk(p);
        return d.isFile() || d.isSymbolicLink() ? [p] : [];
      });

let cache = {};
try {
  cache = JSON.parse(readFileSync(CACHE, 'utf8'));
} catch {
  cache = {};
}
const usedKeys = new Set();

const problems = [];
const entries = {};
const unknown = [];
let ffprobe = null;
for (const abs of walk(MEDIA).sort()) {
  const ext = extname(abs).slice(1).toLowerCase();
  const kind = kindOf(ext);
  const relPath = relative(MEDIA, abs).split('\\').join('/');
  if (!kind) {
    unknown.push(relPath);
    continue;
  }
  const id = relPath.slice(0, -(ext.length + 1));
  if (entries[id]) {
    problems.push(`two files for "${id}": ${entries[id].file} and media/${relPath}`);
    continue;
  }
  const st = statSync(abs);
  const key = `${relPath}|${st.size}|${st.mtimeMs}`;
  let meta = cache[key];
  if (!meta) {
    ffprobe ??= findFfprobe();
    try {
      meta = probe(ffprobe, abs);
    } catch (e) {
      problems.push(`cannot probe media/${relPath}: ${String(e.message || e).split('\n')[0]}`);
      continue;
    }
    cache[key] = meta;
  }
  usedKeys.add(key);
  entries[id] = {
    file: relative(PUBLIC, abs).split('\\').join('/'),
    kind,
    bytes: st.size,
    durationSec: kind === 'image' ? null : meta.durationSec,
    width: meta.width,
    height: meta.height,
    fps: kind === 'video' ? meta.fps : null,
    frames: kind === 'video' ? meta.frames : null,
  };
}

// Compare with what the films can use.
const expected = expectedMedia();
const byId = new Map(expected.map((e) => [e.id, e]));
for (const [id, e] of Object.entries(entries)) {
  const want = byId.get(id);
  if (!want) {
    unknown.push(`${e.file} (no slot is called "${id}")`);
    continue;
  }
  if (want.kind === 'audio' && e.kind !== 'audio') problems.push(`${e.file}: slot "${id}" expects audio`);
  if (want.kind === 'video' && e.kind !== 'video') problems.push(`${e.file}: slot "${id}" expects a video`);
  if (want.kind === 'image-or-video' && e.kind === 'audio') problems.push(`${e.file}: slot "${id}" expects a picture`);
  if (e.kind !== 'image' && !(e.durationSec > 0)) problems.push(`${e.file}: no duration`);
}

mkdirSync(dirname(OUT), {recursive: true});
// keep only the probes of files that still exist
writeFileSync(CACHE, JSON.stringify(Object.fromEntries(Object.entries(cache).filter(([k]) => usedKeys.has(k))), null, 1));
writeFileSync(
  OUT,
  `// GENERATED by scripts/media-manifest.mjs from public/media/ — do not edit, do not commit (gitignored).
// Regenerate with \`npm run gen\` after adding or replacing media (the Studio hot-reloads it).

export interface MediaEntry {
  /** Path relative to public/, for staticFile(). */
  file: string;
  kind: 'video' | 'image' | 'audio';
  bytes: number;
  durationSec: number | null;
  width: number | null;
  height: number | null;
  fps: number | null;
  frames: number | null;
}

export const MEDIA_MANIFEST: Record<string, MediaEntry> = ${JSON.stringify(entries, null, 2)};
`,
);

const present = expected.filter((e) => entries[e.id]);
const missingRequired = expected.filter((e) => !entries[e.id] && e.required);
const missingOptional = expected.filter((e) => !entries[e.id] && !e.required);
if (!quiet) {
  const pad = (s, n) => String(s).padEnd(n);
  console.log(`media-manifest: public/media/ → src/generated/media-manifest.ts`);
  for (const e of expected) {
    const m = entries[e.id];
    const state = m ? `present  ${m.file}${m.durationSec ? ` (${m.durationSec.toFixed(2)} s)` : ''}` : e.required ? 'missing  → placeholder / silence' : 'missing  (optional)';
    console.log(`  ${pad(e.id, 22)} ${pad(e.kind, 15)} ${pad(e.usedBy, 26)} ${state}`);
  }
}
for (const u of unknown) console.warn(`media-manifest: WARNING unused file public/media/${u}`);
console.log(
  `media-manifest: ${present.length}/${expected.length} slots have media; ${missingRequired.length} required missing (placeholder/silence), ${missingOptional.length} optional missing`,
);
if (problems.length) {
  for (const p of problems) console.error(`media-manifest: ERROR ${p}`);
  process.exit(1);
}
